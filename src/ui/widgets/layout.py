"""Схема зала. Меняется вместе с кодом, в БД хранится только номер места (bookings.seat_no)."""
from typing import Dict, List, Tuple, Union

CABINET_LABEL = "Кабинет Анны А."

# Ячейка места руководителя. Подпись — короткое имя сотрудника, которого админ выбрал в «Меню админа → Виджеты»
# (WidgetsSetting.boss_id); по нажатию виджет запрашивает полное имя. Руководитель не выбран — ячейка со штриховкой
BOSS_SEAT = "b"

# Элементы сверху вниз:
#   "подпись"                            — помещение на всю ширину (не бронируется, рисуется штриховкой)
#   [верхний ряд, "подпись", нижний ряд] — стол: столешница и места по обе её стороны.
#                                          Стол рисуется отдельным «островом», между столами — проход
# Места в ряду слева (окно) направо (коридор):
#   "x"    — место другой команды (штриховка, не бронируется)
#   "b"    — место руководителя (BOSS_SEAT: не бронируется, подпись — руководитель из админки)
#   число  — номер места команды
LayoutCell = Union[int, str]
LayoutItem = Union[str, List[Union[List[LayoutCell], str]]]
OFFICE_LAYOUT: List[LayoutItem] = [
    CABINET_LABEL,
    [["x", "x", "x", "x"], "Стол 1", [1, 2, BOSS_SEAT, "x"]],
    [[3, 4, 5, 6], "Стол 2", [7, 8, 9, 10]],
]

# Сколько верхних элементов (помещений) идёт до столов. Подписи «← Окно» / «Коридор →» (окно слева, коридор справа)
# виджет рисует в проходе сразу после первого стола
LAYOUT_TOP_ROWS = 1


def _team_seats() -> Tuple[int, ...]:
    seats = []
    for item in OFFICE_LAYOUT:
        if isinstance(item, str):
            continue
        top, _, bottom = item
        seats.extend(c for c in (*top, *bottom) if isinstance(c, int) and not isinstance(c, bool))
    return tuple(sorted(seats))


# Номера мест команды по порядку автоподбора. Сейчас мест 10 (1–10).
# Каждая бронь получает первое свободное место (BookingService.pick_seat), в том числе когда виджеты выключены в админке.
# Сколько броней на день, решает лимит office_capacity_weekdays.capacity, а не схема: если лимит больше
# len(SEATS), брони сверх числа мест создаются без номера места (seat_no = NULL).
# Для текстового режима это незаметно. В виджетах держите capacity <= len(SEATS): виджет рассчитан на схему,
# человек без места видит «Бронь есть, но место не выбрано», а в дайджесте-виджете его нет вовсе.
SEATS: Tuple[int, ...] = _team_seats()


def _seat_numbers() -> Dict[LayoutCell, int]:
    """Номер места на схеме: места команды и руководителя подряд, столы сверху вниз, в столе верхний ряд, затем
    нижний, в ряду от окна к коридору. Чужие места ("x") номера не получают"""
    out: Dict[LayoutCell, int] = {}
    for item in OFFICE_LAYOUT:
        if isinstance(item, str):
            continue
        top, _, bottom = item
        for c in (*top, *bottom):
            if c == BOSS_SEAT or (isinstance(c, int) and not isinstance(c, bool)):
                out[c] = len(out) + 1
    return out


# Номер на схеме, только для вида (Rich-экран дня): ячейка схемы (seat_no или BOSS_SEAT) → номер.
# Сейчас Стол 1: 1, 2, 3 у руководителя; Стол 2: 4-11. В БД остаётся seat_no (у руководителя номера нет),
# миграции не нужно: номера мест пользователю больше нигде не показываются.
# Номер больше 12 требует новой картинки (SEAT_BADGE в src/ui/rich/emoji.py), до тех пор он пишется цифрами
SEAT_NUMBERS: Dict[LayoutCell, int] = _seat_numbers()
